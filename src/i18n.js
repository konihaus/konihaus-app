try {
  const saved = localStorage.getItem("konihaus.lang");
  const nav = (navigator.language || "en").slice(0, 2);
  lang = saved && dict[saved] ? saved : (dict[nav] ? nav : "en");
} catch (e) { /* ignore */ }

